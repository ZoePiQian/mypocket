"use strict";
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");
const root = path.resolve(__dirname, "..");
function guideContent() {
  const markdown = fs.readFileSync(path.join(root, "INTRODUCTION.md"), "utf8"), images = {}, imageSizes = {};
  for (const match of markdown.matchAll(/^!\[[^\]\r\n]*\]\(([^\r\n]+)\)\s*$/gm)) {
    const name = match[1], resolved = path.resolve(root, name);
    if (!resolved.startsWith(root + path.sep) || !/\.(png|jpg|jpeg|webp)$/i.test(name)) throw new Error(`Guide image must be a local raster asset: ${name}`);
    const extension = path.extname(name).slice(1).toLowerCase(), mime = extension === "jpg" ? "jpeg" : extension;
    const bytes = fs.readFileSync(resolved);
    images[name] = `data:image/${mime};base64,${bytes.toString("base64")}`;
    if (extension === "png" && bytes.length >= 24 && bytes.subarray(0, 8).equals(Buffer.from([137,80,78,71,13,10,26,10])))
      imageSizes[name] = { width: bytes.readUInt32BE(16), height: bytes.readUInt32BE(20) };
  }
  return { markdown, images, imageSizes };
}
function createBundle() {
  const manifest = JSON.parse(fs.readFileSync(path.join(root, "manifest.json"), "utf8"));
  const names = fs.readdirSync(path.join(root, "src")).filter(name => name.endsWith(".js")).sort();
  const sources = names.map(name => `"./${name.slice(0,-3)}": function(module, exports, require) {\n${fs.readFileSync(path.join(root, "src", name), "utf8")}\n}`);
  sources.push(`"./guide-content": function(module) { module.exports = ${JSON.stringify(guideContent())}; }`);
  const bundle = `/* ${manifest.name} v${manifest.version} | MIT | Generated by scripts/build.js */\n"use strict";\nconst externalRequire = require;\nconst modules = {${sources.join(",\n")}};\nconst cache = {};\nfunction localRequire(id) {\n if (id === "obsidian") return externalRequire(id);\n if (!modules[id]) throw new Error("Unknown module: " + id);\n if (!cache[id]) { const m = {exports: {}}; cache[id] = m; modules[id](m, m.exports, localRequire); }\n return cache[id].exports;\n}\nmodule.exports = localRequire("./main");\n`;
  new vm.Script(bundle, { filename: "main.js" }); return bundle;
}
function build() {
  const bundle = createBundle(), output = path.join(root, "安装文件", "local-finance-notes");
  fs.mkdirSync(output, { recursive: true });
  fs.writeFileSync(path.join(output, "main.js"), bundle, "utf8");
  for (const file of ["manifest.json", "styles.css"]) fs.copyFileSync(path.join(root, file), path.join(output, file));
  console.log("Built 安装文件/local-finance-notes (3 installable files, offline guide included)");
}
if (require.main === module) build();
module.exports = { createBundle, guideContent, build };
